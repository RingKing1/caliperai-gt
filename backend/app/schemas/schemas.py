# Cross-module string forward refs (catalog <-> scene -> task) are resolved
# after every domain module is imported. The facade globals contain every
# schema class, so they are supplied as the resolution namespace, mirroring
# the former monolithic module where all classes shared one namespace.
_schema_namespace = {
    name: obj
    for name, obj in globals().items()
    if name in __all__ and isinstance(obj, type)
}

DatasetDetailResponse.model_rebuild(_types_namespace=_schema_namespace)
SceneResponse.model_rebuild(_types_namespace=_schema_namespace)
